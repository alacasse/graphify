def test_install_surface_statuses_decides_file_fingerprint_from_observed_facts() -> None:
    notes_text = f"# Notes\n\n{install_surface_state.USER_SENTINEL}\n\n## graphify\n{install_surface_state.STALE_GRAPHIFY_SENTINEL}\n"

    assert install_surface_statuses.file_fingerprint_from_observation(
        install_surface_statuses.FileFingerprintObservation(exists=False)
    ) == {"exists": False}
    assert install_surface_statuses.file_fingerprint_from_observation(
        install_surface_statuses.FileFingerprintObservation(exists=True, kind="dir")
    ) == {"exists": True, "kind": "dir"}

    fingerprint = install_surface_statuses.file_fingerprint_from_observation(
        install_surface_statuses.FileFingerprintObservation(
            exists=True,
            kind="file",
            data=notes_text.encode("utf-8"),
            text=notes_text,
        ),
        "## graphify",
        install_surface_models.TextExpectation(preserve_user_content=True, repair_stale_graphify_section=True),
    )

    assert fingerprint["exists"] is True
    assert fingerprint["kind"] == "file"
    assert fingerprint["size"] == len(notes_text.encode("utf-8"))
    assert fingerprint["marker_count"] == 1
    assert fingerprint["user_content_preserved"] is True
    assert fingerprint["stale_graphify_present"] is True
    assert isinstance(fingerprint["sha256"], str)
